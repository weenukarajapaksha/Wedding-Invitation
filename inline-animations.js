/* Regenerates assets/animations.js from the .lottie files in assets/.
 *
 * The hero animations are inlined as base-64 because a page opened straight
 * from disk (file://) is not allowed to fetch a local file, which would leave
 * the hero blank when you double-click index.html.
 *
 * Run from the project root after replacing any .lottie file:
 *   node inline-animations.js
 */
const fs = require('fs');
const path = require('path');

// global name -> source file
const sources = {
  COUPLE_LOTTIE: 'assets/couple-animation.lottie',
  BACKDROP_LOTTIE: 'assets/backdrop-animation.lottie'
};

const lines = [
  '/* Generated by inline-animations.js - do not edit by hand.',
  ' *',
  ' * Base-64 copies of the .lottie files in this folder, inlined so the hero',
  ' * animations also play when index.html is opened straight from disk.',
  ' * Regenerate with: node inline-animations.js',
  ' */',
  ''
];

for (const name of Object.keys(sources)) {
  const file = sources[name];
  const b64 = fs.readFileSync(path.join(__dirname, file)).toString('base64');
  lines.push('window.' + name + ' = "data:application/octet-stream;base64,' + b64 + '";');
}

const out = path.join(__dirname, 'assets/animations.js');
fs.writeFileSync(out, lines.join('\n') + '\n');
console.log('wrote ' + out + ' (' + fs.statSync(out).size + ' bytes)');
